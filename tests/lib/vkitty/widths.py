"""Unicode width and grapheme break lookups with the rules of a Ghostty version.

    tables_for(profile)             the Tables of a profile: ghostty-1.3.1 (Unicode 17.0.0, the
                                    uucode 0.2.0 break rules) or ghostty-1.4.0 (Unicode 18.0.0,
                                    the break rules of its uucode)
    Tables.wcwidth(cp)              0, 1 or 2 cells (Ghostty's `width`)
    Tables.props(cp)                (width, zero_in_grapheme, gb, emoji_vs_base), cached
    Tables.grapheme_break(cp1, cp2, st)  (is_break, new_state) with the break state st

The module-level wcwidth, props, grapheme_break and the other names are those of the
ghostty-1.3.1 tables, the oldest supported version and the library default.

The tables come from widths_data.py (uucode 0.2.0, Unicode 17.0.0) and widths_data_140.py
(Ghostty 1.4.0's uucode, Unicode 18.0.0), generated by tools/gen_widths.py. The break rules are
widths_rules.py and widths_rules14.py. grapheme_break reads a table precomputed for every
(state, gb1, gb2), the same idea as the precomputed table in Ghostty's src/unicode/grapheme.zig.
"""
import bisect
import functools

from vkitty import widths_data as _data131
from vkitty import widths_rules as _rules131

MAX_CP = 0x10FFFF


def _split(rows, with_value):
    starts = [row[0] for row in rows]
    ends = [row[1] for row in rows]
    values = [row[2] for row in rows] if with_value else None
    return starts, ends, values


def _in_ranges(starts, ends, cp):
    i = bisect.bisect_right(starts, cp) - 1
    return i >= 0 and cp <= ends[i]


def _value_in_ranges(starts, ends, values, cp, default):
    i = bisect.bisect_right(starts, cp) - 1
    if i >= 0 and cp <= ends[i]:
        return values[i]
    return default


class Tables:
    """The width and grapheme break lookups of one set of generated tables and break rules."""

    def __init__(self, data, rules):
        self.rules = rules
        self.BREAK_STATES = rules.BREAK_STATES
        self.NC_CLASSES = rules.NC_CLASSES
        self.GB_NAMES = tuple(data.GB_NAMES)
        self.UNICODE_VERSION = data.UNICODE_VERSION
        if self.GB_NAMES != self.NC_CLASSES:
            raise ImportError("the widths tables do not match their rules' NC_CLASSES; "
                              "regenerate them with tools/gen_widths.py")
        self.GB_INDEX = {name: i for i, name in enumerate(self.NC_CLASSES)}
        self.STATE_INDEX = {name: i for i, name in enumerate(self.BREAK_STATES)}
        self.GB_OTHER = self.GB_INDEX["other"]
        self.STATE_DEFAULT = self.STATE_INDEX["default"]
        self._w = _split(data.WIDTH, True)
        self._z = _split(data.ZERO_IN_GRAPHEME, False)
        self._g = _split(data.GB, True)
        self._v = _split(data.VS_BASE, False)
        self.props = functools.lru_cache(maxsize=65536)(self._props)
        self._ncls = len(self.NC_CLASSES)
        self._table = self._build_break_table()

    def wcwidth(self, cp):
        """Ghostty's width of one code point: 0, 1 or 2. Above U+10FFFF the width is 1."""
        if 0x20 <= cp < 0x7F:
            return 1
        if cp > MAX_CP:
            return 1
        return _value_in_ranges(self._w[0], self._w[1], self._w[2], cp, 1)

    def _props(self, cp):
        """(width, zero_in_grapheme, gb_no_control, emoji_vs_base) of a code point.

        Above U+10FFFF this is Ghostty's fallback (src/unicode/props_uucode.zig):
        width 1, zero in grapheme, class other, not a VS base."""
        if cp > MAX_CP:
            return (1, True, self.GB_OTHER, False)
        width = self.wcwidth(cp)
        zero = _in_ranges(self._z[0], self._z[1], cp)
        gb = _value_in_ranges(self._g[0], self._g[1], self._g[2], cp, self.GB_OTHER)
        vs = _in_ranges(self._v[0], self._v[1], cp)
        return (width, zero, gb, vs)

    def compute_grapheme_break(self, gb1, gb2, state):
        """The break rule on class and state indices (not the table): used to build the
        table and by the spec to check it."""
        is_break, new_state = self.rules.compute_grapheme_break(
            self.NC_CLASSES[gb1], self.NC_CLASSES[gb2], self.BREAK_STATES[state])
        return is_break, self.STATE_INDEX[new_state]

    def _build_break_table(self):
        n = self._ncls
        table = [None] * (len(self.BREAK_STATES) * n * n)
        for state in range(len(self.BREAK_STATES)):
            for gb1 in range(n):
                for gb2 in range(n):
                    table[(state * n + gb1) * n + gb2] = self.compute_grapheme_break(gb1, gb2,
                                                                                      state)
        return tuple(table)

    def grapheme_break_classes(self, gb1, gb2, state):
        """Table lookup on class and state indices."""
        return self._table[(state * self._ncls + gb1) * self._ncls + gb2]

    def grapheme_break(self, cp1, cp2, state):
        """Is there a grapheme break between cp1 and cp2, given the state after the
        pairs before it? Returns (is_break, new_state); start with state 0."""
        return self._table[(state * self._ncls + self.props(cp1)[2]) * self._ncls
                           + self.props(cp2)[2]]


_T131 = Tables(_data131, _rules131)
_T140 = []


def tables_for(profile):
    """The Tables of a profile (kgp.GHOSTTY_131, kgp.GHOSTTY_140; the kitty profile uses the
    newer Ghostty tables, as it never did anything else than follow the library default)."""
    if profile == "ghostty-1.4.0":
        if not _T140:
            from vkitty import widths_data_140, widths_rules14
            _T140.append(Tables(widths_data_140, widths_rules14))
        return _T140[0]
    return _T131


# the ghostty-1.3.1 tables, under the names this module had before there were two versions
BREAK_STATES = _T131.BREAK_STATES
NC_CLASSES = _T131.NC_CLASSES
GB_NAMES = _T131.GB_NAMES
UNICODE_VERSION = _T131.UNICODE_VERSION
GB_INDEX = _T131.GB_INDEX
STATE_INDEX = _T131.STATE_INDEX
GB_OTHER = _T131.GB_OTHER
STATE_DEFAULT = _T131.STATE_DEFAULT
wcwidth = _T131.wcwidth
props = _T131.props
compute_grapheme_break = _T131.compute_grapheme_break
grapheme_break_classes = _T131.grapheme_break_classes
grapheme_break = _T131.grapheme_break
