use super::color::{quantize, Rgb, Rgba};
use super::registry::default_for;

/// The known port for `colors_name` (Neovim's `g:colors_name`) on a `kind`
/// background: the first port with an alias of that name whose kind is
/// none or `kind`.
pub fn lookup(colors_name: &str, kind: Kind) -> Option<&'static Port> {
    PORTS.iter().find(|p| p.aliases.iter().any(|&(name, k)| name == colors_name && k.is_none_or(|k| k == kind)))
}

impl Port {
    /// The port's color for the VS Code color id `id`, with its alpha.
    pub fn color(&self, id: &str) -> Option<Rgba> {
        self.colors.iter().find(|(k, _)| *k == id).map(|&(_, v)| {
            let ch = |shift: u32| ((v >> shift) & 0xff) as f64;
            Rgba::new(ch(24), ch(16), ch(8), ch(0) / 255.0)
        })
    }

    /// The scheme's own color for a token no VS Code color id carries.
    pub fn completion(&self, t: Token) -> Option<Rgb> {
        self.completions.iter().find(|(k, _)| *k == t).map(|&(_, v)| Rgb::from_u32(v >> 8))
    }

    /// The port's `editor.background` (every port in the table defines it;
    /// VS Code's default for the port's kind otherwise).
    pub fn bg(&self) -> Rgb {
        let kind = if self.light { Kind::Light } else { Kind::Dark };
        quantize(self.color("editor.background").unwrap_or_else(|| default_for("editor.background", kind)))
    }
}
