//! The known ports: for a Neovim colorscheme, the colors its VS Code port defines (the
//! theme extension named in `source`, resolved with its includes), for the color ids the
//! palette rules read. `completions` hold the scheme's own colors for tokens no VS Code
//! color id carries (tokyonight: `dark5`, `comment` and `green` of tokyonight.nvim's
//! palette, the same in storm and night). Colors are 0xRRGGBBAA. A port matches when
//! `vim.g.colors_name` equals an alias name and, when the alias names one, `background`
//! equals its kind.

